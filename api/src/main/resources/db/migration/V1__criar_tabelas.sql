-- =====================================================================
-- Geladeira Solidaria Inteligente - V1: estrutura das tabelas
-- Mesmo modelo da disciplina de Banco de Dados, adaptado para PostgreSQL.
-- =====================================================================

CREATE TABLE geladeira (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome            VARCHAR(100)  NOT NULL,
    endereco        VARCHAR(150)  NOT NULL,
    bairro          VARCHAR(60)   NOT NULL,
    cidade          VARCHAR(60)   NOT NULL,
    latitude        NUMERIC(9,6),
    longitude       NUMERIC(9,6),
    capacidade_kg   NUMERIC(8,2)  NOT NULL CHECK (capacidade_kg > 0),
    responsavel     VARCHAR(100)  NOT NULL,
    status          VARCHAR(15)   NOT NULL CHECK (status IN ('ATIVA','MANUTENCAO','INATIVA')),
    dt_instalacao   DATE          NOT NULL
);

CREATE TABLE doador (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome            VARCHAR(100)  NOT NULL,
    tipo            VARCHAR(2)    NOT NULL CHECK (tipo IN ('PF','PJ')),
    telefone        VARCHAR(20),
    email           VARCHAR(120)  NOT NULL UNIQUE,
    dt_cadastro     DATE          NOT NULL
);

CREATE TABLE categoria (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome            VARCHAR(60)   NOT NULL UNIQUE,
    refrigerado     BOOLEAN       NOT NULL,
    temp_max_c      NUMERIC(4,1)
);

CREATE TABLE leitura_sensor (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_geladeira    BIGINT        NOT NULL REFERENCES geladeira(id),
    dt_leitura      TIMESTAMP     NOT NULL,
    temperatura_c   NUMERIC(4,1)  NOT NULL,
    umidade_pct     NUMERIC(5,2),
    porta_aberta    BOOLEAN       NOT NULL
);

CREATE TABLE doacao (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_geladeira    BIGINT        NOT NULL REFERENCES geladeira(id),
    id_doador       BIGINT        NOT NULL REFERENCES doador(id),
    id_categoria    BIGINT        NOT NULL REFERENCES categoria(id),
    descricao       VARCHAR(120)  NOT NULL,
    quantidade_kg   NUMERIC(8,2)  NOT NULL CHECK (quantidade_kg > 0),
    dt_doacao       TIMESTAMP     NOT NULL,
    dt_validade     DATE          NOT NULL,
    status          VARCHAR(15)   NOT NULL CHECK (status IN ('DISPONIVEL','RETIRADA','DESCARTADA')),
    nivel_risco     VARCHAR(10)   NOT NULL CHECK (nivel_risco IN ('OK','ATENCAO','CRITICO','VENCIDO'))
);

CREATE TABLE alerta (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_geladeira    BIGINT        NOT NULL REFERENCES geladeira(id),
    id_doacao       BIGINT        REFERENCES doacao(id),
    tipo            VARCHAR(15)   NOT NULL CHECK (tipo IN ('TEMPERATURA','VALIDADE','CAPACIDADE','ESTOQUE_BAIXO')),
    nivel           VARCHAR(10)   NOT NULL CHECK (nivel IN ('INFO','ALTO','CRITICO')),
    mensagem        VARCHAR(300)  NOT NULL,
    dt_alerta       TIMESTAMP     NOT NULL,
    resolvido       BOOLEAN       NOT NULL
);

-- Usuarios da API (login JWT). Um usuario DOADOR fica ligado ao seu cadastro de doador.
CREATE TABLE usuario (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome            VARCHAR(100)  NOT NULL,
    email           VARCHAR(120)  NOT NULL UNIQUE,
    senha           VARCHAR(100)  NOT NULL,
    papel           VARCHAR(15)   NOT NULL CHECK (papel IN ('ADMIN','VOLUNTARIO','DOADOR','SENSOR')),
    id_doador       BIGINT        REFERENCES doador(id),
    ativo           BOOLEAN       NOT NULL,
    dt_cadastro     TIMESTAMP     NOT NULL
);

CREATE INDEX idx_doacao_geladeira_status ON doacao (id_geladeira, status);
CREATE INDEX idx_doacao_validade         ON doacao (dt_validade);
CREATE INDEX idx_leitura_geladeira_data  ON leitura_sensor (id_geladeira, dt_leitura);
CREATE INDEX idx_alerta_aberto           ON alerta (resolvido, id_geladeira);
